import math

# Handy constants

C = 299792.458                  # speed of light in km/s
C_INVERSE = 1. / C

RPD = math.pi / 180.            # radians per degree
DPR = 180. / math.pi            # degrees per radian
SPR = 3600. * 180. / math.pi    # arcseconds per radian
RPS = math.pi / (3600. * 180.)  # radians per arcsecond
SPD = 86400.                    # seconds per day

AU = 149597870.7                # Astronomical Unit in km

PI = math.pi
TWOPI = 2. * math.pi
HALFPI = math.pi / 2.

